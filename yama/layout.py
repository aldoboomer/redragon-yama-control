# Teclas G en el mapa de teclas (no en los LEDs). Columna-mayor, 8 filas por
# columna; las G están en la fila 7 alternando G1, G7, G2, G8, ...
# Valor de fábrica: 06 cc cc con cc = 0x11 + n (reproduce la macro grabada con Rec).
G_KEY_INDEX = {}
for col in range(12):
    n = col // 2 + 1 if col % 2 == 0 else col // 2 + 7
    G_KEY_INDEX[n] = col * 8 + 7


def g_default_entry(n: int) -> bytes:
    code = 0x11 + n
    return bytes((0x06, code, code))


def g_macro_entry(macro_index: int) -> bytes:
    return bytes((0x05, 0x01, macro_index))
